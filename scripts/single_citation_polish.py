def main() -> None:
    doc = Document(str(INPUT))
    changed = []
    for paragraph in doc.paragraphs:
        text = paragraph.text
        for anchor, replacement in REWRITES.items():
            if anchor in text:
                if isinstance(replacement, tuple):
                    new_text = replacement[0]
                else:
                    new_text = text.replace(anchor, replacement)
                if new_text != text:
                    set_paragraph_text(paragraph, new_text)
                    changed.append(anchor)
                break
    for index, replacement in INDEX_REWRITES.items():
        if index >= len(doc.paragraphs):
            raise IndexError(f"paragraph index {index} is outside the document")
        set_paragraph_text(doc.paragraphs[index], replacement)
    doc.save(str(OUTPUT))
    print(f"saved {OUTPUT}")
    print(f"rewritten {len(changed)} paragraphs and normalized {len(INDEX_REWRITES)} full paragraphs")


if __name__ == "__main__":
    main()
